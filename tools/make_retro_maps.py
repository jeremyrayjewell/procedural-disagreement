"""Writes the two retro test maps for the room shell: 64 x 64 seamless grey modulation maps.

    python tools/make_retro_maps.py

Deterministic (fixed seeds), seamless by construction (band-limited periodic noise built in the
frequency domain). Grey only, mean at the middle (0.5 in the map is a factor of 1.0 on the
object's own colour). No grime, no marks, no imagery.

    retro_ps1_01  late-PS1-like: mottling plus per-texel grain, quantised to 8 levels through a
                  4 x 4 ordered dither; to be sampled nearest-neighbour.
    retro_floor_01  the shell recipe with its own seeds, for the chamber floor.
    retro_prop_01  16 x 16, 4 levels, stretched once per face: the room's props.
    retro_n64_01  N64-like: broader, softer mottling, little grain, not quantised; to be sampled
                  bilinearly.
"""

import os

import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "assets", "textures", "room_shell")
N = 64
BAYER = np.array([[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]) / 16.0 - 0.5


def band(seed, low, high, n=N):
    """Periodic noise with features between `low` and `high` texels across, unit deviation."""
    rng = np.random.default_rng(seed)
    f = np.fft.fft2(rng.standard_normal((n, n)))
    k = np.hypot(*np.meshgrid(np.fft.fftfreq(n), np.fft.fftfreq(n)))
    # A soft 1/f spectrum between the two sizes (no hard band, which would draw worm-like shapes).
    k[0, 0] = 1.0
    weight = 1.0 / k * np.exp(-((k * low) ** 2)) * (1.0 - np.exp(-((k * high) ** 2)))
    weight[0, 0] = 0.0
    n = np.real(np.fft.ifft2(f * weight))
    return (n - n.mean()) / n.std()


def write(folder, values, note):
    os.makedirs(os.path.join(OUT, folder), exist_ok=True)
    Image.fromarray(np.clip(np.round(values * 255.0), 0, 255).astype(np.uint8)).save(
        os.path.join(OUT, folder, "modulation.png"))
    with open(os.path.join(OUT, folder, "SOURCE.txt"), "w", encoding="utf-8", newline="\n") as f:
        f.write(note)


def main():
    # PS1: mottling at 6-24 texels plus per-texel grain; 8 levels through an ordered dither.
    v = 0.75 * band(11, 6, 24) + 0.35 * band(12, 1.5, 3) + 0.30 * np.random.default_rng(13).standard_normal((N, N))
    v = 0.5 + 0.17 * v / v.std()
    levels = 8
    q = np.floor(v * (levels - 1) + 0.5 + BAYER[np.arange(N)[:, None] % 4, np.arange(N)[None, :] % 4]) / (levels - 1)
    q += 0.5 - q.mean()
    write("retro_ps1_01", q, "Generated by tools/make_retro_maps.py (deterministic). 64 x 64 grey, seamless.\n"
          "Late-PS1-like test map: mottling plus per-texel grain, 8 levels through a 4 x 4 ordered dither.\n"
          "Sampled nearest-neighbour as a multiplier (mean 1.0) on the object's own colour.\n"
          "Approved 2026-10-19 for the room shell at 10 cm texels (+-20%; ceiling +-11%).\n")
    # The chamber floor: the same recipe as the shell's map, its own seeds.
    v = 0.75 * band(31, 6, 24) + 0.35 * band(32, 1.5, 3) + 0.30 * np.random.default_rng(33).standard_normal((N, N))
    v = 0.5 + 0.17 * v / v.std()
    q = np.floor(v * (levels - 1) + 0.5 + BAYER[np.arange(N)[:, None] % 4, np.arange(N)[None, :] % 4]) / (levels - 1)
    q += 0.5 - q.mean()
    write("retro_floor_01", q, "Generated by tools/make_retro_maps.py (deterministic). 64 x 64 grey, seamless.\n"
          "Chamber-floor test map: the shell map's recipe (mottling plus per-texel grain, 8 levels through a\n"
          "4 x 4 ordered dither) with its own seeds. Colour multiply (mean 1.0), 20 cm texels, +-20%. Approved 2026-10-19.\n")
    # The station level's structure: the shell recipe with its own seeds.
    v = 0.75 * band(61, 6, 24) + 0.35 * band(62, 1.5, 3) + 0.30 * np.random.default_rng(63).standard_normal((N, N))
    v = 0.5 + 0.17 * v / v.std()
    q = np.floor(v * (levels - 1) + 0.5 + BAYER[np.arange(N)[:, None] % 4, np.arange(N)[None, :] % 4]) / (levels - 1)
    q += 0.5 - q.mean()
    write("retro_level_01", q, "Generated by tools/make_retro_maps.py (deterministic). 64 x 64 grey, seamless.\n"
          "Station-level structure map (routing, station bodies, platforms, aprons): the shell recipe with\n"
          "its own seeds. Colour multiply (mean 1.0). Test.\n")
    # The landfill's waste ground: the shell recipe with its own seeds.
    v = 0.75 * band(71, 6, 24) + 0.35 * band(72, 1.5, 3) + 0.30 * np.random.default_rng(73).standard_normal((N, N))
    v = 0.5 + 0.17 * v / v.std()
    q = np.floor(v * (levels - 1) + 0.5 + BAYER[np.arange(N)[:, None] % 4, np.arange(N)[None, :] % 4]) / (levels - 1)
    q += 0.5 - q.mean()
    write("retro_waste_01", q, "Generated by tools/make_retro_maps.py (deterministic). 64 x 64 grey, seamless.\n"
          "Landfill waste-ground map: the shell recipe with its own seeds. Colour multiply (mean 1.0). Test.\n")
    # Props: one 16 x 16 texture stretched once over each face, 4 grey levels, no dither: a
    # cruder, more graphic family than the architecture's.
    v = 0.8 * band(51, 2, 8, 16) + 0.45 * np.random.default_rng(52).standard_normal((16, 16))
    v = (v - v.mean()) / v.std()
    q = np.clip(np.floor(v * 0.9 + 2.0), 0, 3) / 3.0
    q += 0.5 - q.mean()
    write("retro_prop_01", q, "Generated by tools/make_retro_maps.py (deterministic). 16 x 16 grey.\n"
          "Prop map: stretched once over each face of a prop (the room's cabinets, carriages and lamp\n"
          "housing), 4 levels, no dither, with a flat tone per face. Colour multiply (mean 1.0).\n"
          "Approved 2026-10-19 (X3).\n")
    # N64: broader, softer mottling at 10-40 texels, a little mid detail, no quantisation.
    v = 0.85 * band(21, 10, 40) + 0.35 * band(22, 3, 8)
    v = 0.5 + 0.17 * v / v.std()
    v += 0.5 - v.mean()
    write("retro_n64_01", v, "Generated by tools/make_retro_maps.py (deterministic). 64 x 64 grey, seamless.\n"
          "N64-like test map: broad soft mottling, little grain, not quantised.\n"
          "Sampled bilinearly as a multiplier (mean 1.0) on the object's own colour, and on roughness. Not approved.\n")
    print("wrote", os.path.join(OUT, "retro_ps1_01"), os.path.join(OUT, "retro_floor_01"), os.path.join(OUT, "retro_n64_01"))


main()
